'use client';
import { useState, useEffect, useCallback } from 'react';
import { ScDisciplineService } from '../services/sc-discipline.service';
import { createClient } from '@/lib/supabase/client';
import type { Discipline, DisciplineCreate } from '@educi/types';

export const useScDisciplineList = (schoolId: string) => {
  const [items, setItems] = useState<Discipline[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const fetchData = useCallback(async () => {
    try {
      setLoading(true);
      const service = new ScDisciplineService(createClient());
      const data = await service.listDisciplines(schoolId);
      setItems(data);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unknown error');
    } finally {
      setLoading(false);
    }
  }, [schoolId]);
  useEffect(() => { fetchData(); }, [fetchData]);
  return { items, loading, error, refresh: fetchData };
};

export const useScDisciplineGet = (schoolId: string, id: string | null) => {
  const [item, setItem] = useState<Discipline | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const fetchItem = useCallback(async () => {
    if (!id) { setLoading(false); return; }
    try {
      setLoading(true);
      const service = new ScDisciplineService(createClient());
      const data = await service.getDiscipline(schoolId, id);
      setItem(data);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unknown error');
    } finally {
      setLoading(false);
    }
  }, [schoolId, id]);
  useEffect(() => { fetchItem(); }, [fetchItem]);
  return { item, loading, error, refresh: fetchItem };
};

export const useScDisciplineCreate = (schoolId: string) => {
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const create = useCallback(async (data: DisciplineCreate): Promise<Discipline | null> => {
    try {
      setLoading(true);
      const service = new ScDisciplineService(createClient());
      const result = await service.createDiscipline(schoolId, data);
      return result;
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unknown error');
      return null;
    } finally {
      setLoading(false);
    }
  }, [schoolId]);
  return { create, loading, error };
};

