'use client';
import { useState, useEffect, useCallback } from 'react';
import { ScAllergenService } from '../services/sc-allergen.service';
import { createClient } from '@/lib/supabase/client';
import type { Allergen, AllergenCreate } from '@educi/types';

export const useScAllergenList = (schoolId: string) => {
  const [items, setItems] = useState<Allergen[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const fetchData = useCallback(async () => {
    try {
      setLoading(true);
      const service = new ScAllergenService(createClient());
      const data = await service.listAllergens(schoolId);
      setItems(data);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unknown error');
    } finally {
      setLoading(false);
    }
  }, [schoolId]);
  useEffect(() => { fetchData(); }, [fetchData]);
  return { items, loading, error, refresh: fetchData };
};

export const useScAllergenGet = (schoolId: string, id: string | null) => {
  const [item, setItem] = useState<Allergen | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const fetchItem = useCallback(async () => {
    if (!id) { setLoading(false); return; }
    try {
      setLoading(true);
      const service = new ScAllergenService(createClient());
      const data = await service.getAllergen(schoolId, id);
      setItem(data);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unknown error');
    } finally {
      setLoading(false);
    }
  }, [schoolId, id]);
  useEffect(() => { fetchItem(); }, [fetchItem]);
  return { item, loading, error, refresh: fetchItem };
};

