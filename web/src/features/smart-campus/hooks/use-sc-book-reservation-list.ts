'use client';
import { useState, useEffect, useCallback } from 'react';
import { ScBookReservationService } from '../services/sc-book-reservation.service';
import { createClient } from '@/lib/supabase/client';
import type { BookReservation, BookReservationCreate } from '@educi/types';

export const useScBookReservationList = (schoolId: string) => {
  const [items, setItems] = useState<BookReservation[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const fetchData = useCallback(async () => {
    try {
      setLoading(true);
      const service = new ScBookReservationService(createClient());
      const data = await service.listReservations(schoolId);
      setItems(data);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unknown error');
    } finally {
      setLoading(false);
    }
  }, [schoolId]);
  useEffect(() => { fetchData(); }, [fetchData]);
  return { items, loading, error, refresh: fetchData };
};

export const useScBookReservationGet = (schoolId: string, id: string | null) => {
  const [item, setItem] = useState<BookReservation | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const fetchItem = useCallback(async () => {
    if (!id) { setLoading(false); return; }
    try {
      setLoading(true);
      const service = new ScBookReservationService(createClient());
      const data = await service.getReservation(schoolId, id);
      setItem(data);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unknown error');
    } finally {
      setLoading(false);
    }
  }, [schoolId, id]);
  useEffect(() => { fetchItem(); }, [fetchItem]);
  return { item, loading, error, refresh: fetchItem };
};

