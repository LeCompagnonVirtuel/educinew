'use client';
import { useState, useEffect, useCallback } from 'react';
import { ScFuelRecordService } from '../services/sc-fuel-record.service';
import { createClient } from '@/lib/supabase/client';
import type { FuelRecord, FuelRecordCreate } from '@educi/types';

export const useScFuelRecordList = (schoolId: string) => {
  const [items, setItems] = useState<FuelRecord[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const fetchData = useCallback(async () => {
    try {
      setLoading(true);
      const service = new ScFuelRecordService(createClient());
      const data = await service.listFuelRecords(schoolId);
      setItems(data);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unknown error');
    } finally {
      setLoading(false);
    }
  }, [schoolId]);
  useEffect(() => { fetchData(); }, [fetchData]);
  return { items, loading, error, refresh: fetchData };
};

export const useScFuelRecordGet = (schoolId: string, id: string | null) => {
  const [item, setItem] = useState<FuelRecord | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const fetchItem = useCallback(async () => {
    if (!id) { setLoading(false); return; }
    try {
      setLoading(true);
      const service = new ScFuelRecordService(createClient());
      const data = await service.getFuelRecord(schoolId, id);
      setItem(data);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unknown error');
    } finally {
      setLoading(false);
    }
  }, [schoolId, id]);
  useEffect(() => { fetchItem(); }, [fetchItem]);
  return { item, loading, error, refresh: fetchItem };
};

