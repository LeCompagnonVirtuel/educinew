'use client';
import { useState, useEffect, useCallback } from 'react';
import { ScBusDriverService } from '../services/sc-bus-driver.service';
import { createClient } from '@/lib/supabase/client';
import type { BusDriver, BusDriverCreate } from '@educi/types';

export const useScBusDriverList = (schoolId: string) => {
  const [items, setItems] = useState<BusDriver[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const fetchData = useCallback(async () => {
    try {
      setLoading(true);
      const service = new ScBusDriverService(createClient());
      const data = await service.listDrivers(schoolId);
      setItems(data);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unknown error');
    } finally {
      setLoading(false);
    }
  }, [schoolId]);
  useEffect(() => { fetchData(); }, [fetchData]);
  return { items, loading, error, refresh: fetchData };
};

export const useScBusDriverGet = (schoolId: string, id: string | null) => {
  const [item, setItem] = useState<BusDriver | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const fetchItem = useCallback(async () => {
    if (!id) { setLoading(false); return; }
    try {
      setLoading(true);
      const service = new ScBusDriverService(createClient());
      const data = await service.getDriver(schoolId, id);
      setItem(data);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unknown error');
    } finally {
      setLoading(false);
    }
  }, [schoolId, id]);
  useEffect(() => { fetchItem(); }, [fetchItem]);
  return { item, loading, error, refresh: fetchItem };
};

export const useScBusDriverCreate = (schoolId: string) => {
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const create = useCallback(async (data: BusDriverCreate): Promise<BusDriver | null> => {
    try {
      setLoading(true);
      const service = new ScBusDriverService(createClient());
      const result = await service.createDriver(schoolId, data);
      return result;
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unknown error');
      return null;
    } finally {
      setLoading(false);
    }
  }, [schoolId]);
  return { create, loading, error };
};

