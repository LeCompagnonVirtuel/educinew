'use client';
import { useState, useEffect, useCallback } from 'react';
import { ScAudiobookService } from '../services/sc-audiobook.service';
import { createClient } from '@/lib/supabase/client';
import type { Audiobook, AudiobookCreate } from '@educi/types';

export const useScAudiobookList = (schoolId: string) => {
  const [items, setItems] = useState<Audiobook[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const fetchData = useCallback(async () => {
    try {
      setLoading(true);
      const service = new ScAudiobookService(createClient());
      const data = await service.listAudiobooks(schoolId);
      setItems(data);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unknown error');
    } finally {
      setLoading(false);
    }
  }, [schoolId]);
  useEffect(() => { fetchData(); }, [fetchData]);
  return { items, loading, error, refresh: fetchData };
};

export const useScAudiobookGet = (schoolId: string, id: string | null) => {
  const [item, setItem] = useState<Audiobook | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const fetchItem = useCallback(async () => {
    if (!id) { setLoading(false); return; }
    try {
      setLoading(true);
      const service = new ScAudiobookService(createClient());
      const data = await service.getAudiobook(schoolId, id);
      setItem(data);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unknown error');
    } finally {
      setLoading(false);
    }
  }, [schoolId, id]);
  useEffect(() => { fetchItem(); }, [fetchItem]);
  return { item, loading, error, refresh: fetchItem };
};

