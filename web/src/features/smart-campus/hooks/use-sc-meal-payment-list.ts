'use client';
import { useState, useEffect, useCallback } from 'react';
import { ScMealPaymentService } from '../services/sc-meal-payment.service';
import { createClient } from '@/lib/supabase/client';
import type { MealPayment, MealPaymentCreate } from '@educi/types';

export const useScMealPaymentList = (schoolId: string) => {
  const [items, setItems] = useState<MealPayment[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const fetchData = useCallback(async () => {
    try {
      setLoading(true);
      const service = new ScMealPaymentService(createClient());
      const data = await service.listPayments(schoolId);
      setItems(data);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unknown error');
    } finally {
      setLoading(false);
    }
  }, [schoolId]);
  useEffect(() => { fetchData(); }, [fetchData]);
  return { items, loading, error, refresh: fetchData };
};

export const useScMealPaymentGet = (schoolId: string, id: string | null) => {
  const [item, setItem] = useState<MealPayment | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const fetchItem = useCallback(async () => {
    if (!id) { setLoading(false); return; }
    try {
      setLoading(true);
      const service = new ScMealPaymentService(createClient());
      const data = await service.getPayment(schoolId, id);
      setItem(data);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unknown error');
    } finally {
      setLoading(false);
    }
  }, [schoolId, id]);
  useEffect(() => { fetchItem(); }, [fetchItem]);
  return { item, loading, error, refresh: fetchItem };
};

